#!/usr/bin/env python3
"""Build plugins/plus-souls/npcids.js: the game's NPC ids of every monster
that drops a pet soul, keyed to the monster's name key in sources.js, so the
Pet Map's radar can tell what it sees spawn (the meter hands it NPC ids).

Matched by English name: public/i18n/npcs/en.json names each NPC id, and
sources.js's SOURCE_TEXT names each monster. A name several monsters share
(the same mob at another level) maps to each of them; the radar keeps only
drops on the map you are on. It also writes the bosses' names and which NPC ids the game names at all
(as runs of ids): the radar marks bosses, and shows the ones it has no name
for as NPCs and objects (they almost never die). Rerun after a patch updates
either file:

    python3 -I tools/citizen-map/build_npcids.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOULS = ROOT / "plugins" / "plus-souls"


def js_object(path, name):
    text = path.read_text(encoding="utf-8")
    start = text.index(f"const {name} = ") + len(f"const {name} = ")
    return json.JSONDecoder().raw_decode(text[start:])[0]


def main():
    sources = js_object(SOULS / "sources.js", "PET_SOURCES")
    texts = js_object(SOULS / "sources.js", "SOURCE_TEXT")
    npcs = json.loads((ROOT / "public" / "i18n" / "npcs" / "en.json").read_text(encoding="utf-8"))

    def english(key):
        value = texts.get(key)
        return value.get("en") if isinstance(value, dict) else value

    by_name = {}
    for pet in sources.values():
        for drop in pet.get("drops", []):
            name = english(drop.get("npc"))
            if name:
                by_name.setdefault(name, set()).add(drop["npc"])
    out = {}
    for npc_id, npc in npcs.items():
        keys = by_name.get(npc.get("name"))
        if keys:
            out[npc_id] = sorted(keys)
    body = json.dumps(out, separators=(",", ":"), sort_keys=True)
    bosses = {
        k: (v["name"] if v.get("name") not in (None, "None", "???") else "")
        for k, v in npcs.items() if v.get("isBoss") and not v.get("isDummy")
    }
    runs = []
    for i in sorted(int(k) for k, v in npcs.items() if not v.get("isDummy")):
        if runs and i == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([i, 1])
    compact = lambda v: json.dumps(v, separators=(",", ":"), sort_keys=True, ensure_ascii=False)
    (SOULS / "npcids.js").write_text(
        "// The game's NPC ids of the monsters that drop pet souls, each to its name\n"
        "// key(s) in sources.js, for the radar. Generated by\n"
        "// tools/citizen-map/build_npcids.py: don't edit by hand.\n"
        f"const NPC_SOURCES = {body};\n"
        "// Bosses, each to its name (empty where the game has none).\n"
        f"const NPC_BOSSES = {compact(bosses)};\n"
        "// The NPC ids the game names, as [first id, how many]: monsters.\n"
        f"const NPC_KNOWN_RUNS = {compact(runs)};\n",
        encoding="utf-8",
    )
    print(f"{len(out)} NPC ids for {len(by_name)} monster names, {len(bosses)} bosses, {len(runs)} runs")


if __name__ == "__main__":
    main()
