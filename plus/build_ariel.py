#!/usr/bin/env python3
"""Build plugins/plus-builds/ariel.js: the Ariel Daevanion board for the planner.

The layout is NCSOFT's own (any character's /api/character/daevanion/detail
with boardId 75 lists every node with its row, column, grade and effects).
The order comes from top players: for each class, the share of its sampled
top players who own each node, then a greedy walk from the centre that always
buys the most-owned node touching what is already bought (ties: cheaper, then
nearer the centre). Classes with few samples borrow the all-class shares.

  build_ariel.py LAYOUT.json SAMPLES.jsonl [...] > plugins/plus-builds/ariel.js

SAMPLES lines: {"cls": "gladiator", "nodes": [nodeId, ...]} (characters whose
Ariel board has nodes; others are ignored).
"""
import json
import statistics
import sys

CLASSES = ["gladiator", "templar", "assassin", "ranger", "sorcerer", "spiritmaster", "cleric", "chanter"]
KIND = {"Common": ("stat", 1), "Rare": ("passive", 2), "Legend": ("skill", 3), "Unique": ("special", 4)}
CELL = 48
MIN_SAMPLES = 15

layout = json.load(open(sys.argv[1]))["nodeList"]
real = [n for n in layout if n["type"] != "None"]
real.sort(key=lambda n: (n["row"], n["col"]))
c0 = min(n["col"] for n in real)
r0 = min(n["row"] for n in real)
size = max(max(n["col"] for n in real) - c0, max(n["row"] for n in real) - r0) + 1

nodes, index, pos = [], {}, {}
for i, n in enumerate(real):
    col, row = n["col"] - c0, n["row"] - r0
    if n["type"] == "Start":
        kind, cost, name, tip = "start", 0, "Ariel", "Start: the board opens outwards from here."
    else:
        kind, cost = KIND[n["grade"]]
        name = n["name"]
        tip = ". ".join(e["desc"] for e in n.get("effectList", []))
    nodes.append([col, row, kind, cost, name, tip])
    index[n["nodeId"] % 10000] = i  # board id × 10,000 + node: the board id differs per class
    pos[(col, row)] = i
start = next(i for i, x in enumerate(nodes) if x[2] == "start")

# Links: every pair of orthogonal neighbours (as the in-game board draws it).
links = []
adj = {i: [] for i in range(len(nodes))}
for (c, r), i in pos.items():
    for dc, dr in ((1, 0), (0, 1)):
        j = pos.get((c + dc, r + dr))
        if j is None:
            continue
        adj[i].append(j)
        adj[j].append(i)
        links.append(f"M{c * CELL + 24} {r * CELL + 24}{'h' if dc else 'v'}{CELL}")

samples = {c: [] for c in CLASSES}
seen = set()
for path in sys.argv[2:]:
    for line in open(path):
        rec = json.loads(line)
        # The same character can come from two sampling runs.
        key = (rec.get("reg"), rec.get("cls"), rec.get("cp"), rec.get("il"), tuple(rec.get("nodes", [])))
        if key in seen:
            continue
        seen.add(key)
        got = [index[x % 10000] for x in rec.get("nodes", []) if x % 10000 in index and index[x % 10000] != start]
        if got and rec.get("cls") in samples:
            samples[rec["cls"]].append(set(got))
everyone = [s for v in samples.values() for s in v]


def shares(sets):
    return [sum(i in s for s in sets) / len(sets) if sets else 0 for i in range(len(nodes))]


def walk(share):
    """Unlock order: the most-owned node touching what's bought, each step."""
    dist = {start: 0}
    queue = [start]
    for i in queue:
        for j in adj[i]:
            if j not in dist:
                dist[j] = dist[i] + 1
                queue.append(j)
    have, order = {start}, [0] * len(nodes)
    frontier = set(adj[start])
    step = 0
    while frontier:
        best = max(frontier, key=lambda j: (round(share[j], 3), -nodes[j][3], -dist[j], -j))
        frontier.discard(best)
        have.add(best)
        step += 1
        order[best] = step
        frontier |= {j for j in adj[best] if j not in have}
    return order


all_share = shares(everyone)
out = {}
for cls in CLASSES:
    sets = samples[cls]
    share = shares(sets) if len(sets) >= MIN_SAMPLES else all_share
    order = walk(share)
    spent = [sum(nodes[i][3] for i in s) for s in (sets if len(sets) >= MIN_SAMPLES else everyone)]
    out[cls] = {
        "spent": int(statistics.median(spent)) if spent else 0,
        "n": len(sets),
        "o": [[order[i], round(share[i] * 100)] for i in range(len(nodes))],
        "skills": {},
    }

print("// Ariel board for the Daevanion planner. Generated by plus/build_ariel.py; don't edit by hand.")
print("// Layout from NCSOFT's character site; order from the boards of each class's")
print(f"// top players on MetaBot's Global leaderboards ({len(everyone)} sampled, October 2026).")
print("// pct: share of that class's sampled top players who own the node (n < "
      f"{MIN_SAMPLES}: all classes').")
print(f"DAEV_LAYOUT.Ariel = {json.dumps({'size': size, 'links': ''.join(links), 'nodes': nodes}, ensure_ascii=False, separators=(',', ':'))};")
for cls in CLASSES:
    print(f"DAEV_ORDER.{cls}.Ariel = {json.dumps(out[cls], separators=(',', ':'))};")
print(f"const ARIEL_SAMPLE = {json.dumps({c: out[c]['n'] for c in CLASSES})};")
print("samples: " + ", ".join(f"{c} {out[c]['n']}" for c in CLASSES), file=sys.stderr)
