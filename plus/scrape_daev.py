"""Pull the Daevanion boards (layout, suggested order, KR pick rates) out of
aion2-meta class guide pages. usage: scrape_daev.py DLDIR OUT.js"""
import re, sys, json, html
dl, out = sys.argv[1], sys.argv[2]
CLASSES = ["gladiator", "templar", "assassin", "ranger", "sorcerer", "spiritmaster", "cleric", "chanter"]
KIND = {"common": "stat", "rare": "passive", "legend": "skill", "unique": "special", "start": "start"}
layout, order, spent = {}, {}, {}
for c in CLASSES:
    s = open(f"{dl}/{c}.html", encoding="utf8").read()
    order[c], spent[c] = {}, {}
    for m in re.finditer(r'<div class="dv-board" data-board="\d+".*?</svg>', s, re.S):
        blk = m.group(0)
        name = re.search(r'aria-label="(\w+) board"', blk).group(1)
        size = int(re.search(r'<svg viewBox="0 0 (\d+) \d+"', blk).group(1))
        spent[c][name] = int(re.search(r'type="range" min="0" max="\d+" value="(\d+)"', blk).group(1))
        links = re.search(r'<path class="links" d="([^"]*)"', blk).group(1)
        nodes, ords = [], []
        for g in re.finditer(r'<g class="n[^"]*" transform="translate\((\d+) (\d+)\)"(.*?)</g>', blk, re.S):
            x, y, rest = int(g.group(1)), int(g.group(2)), g.group(3)
            kind = KIND[re.search(r'node-(\w+)\.webp', rest).group(1)]
            tip = html.unescape(re.search(r'data-tip="([^"]*)"', rest).group(1)).split("\n")[0].strip()
            title = html.unescape(re.search(r'data-tip-title="([^"]*)"', rest).group(1))
            meta = re.search(r'data-tip-meta="(\d+) crystals? · (\d+)%', rest)
            nm = title.split(" · ", 1)[1] if " · " in title else title
            n = int(re.match(r"#(\d+)", title).group(1)) if title.startswith("#") else 0
            cost = int(meta.group(1)) if meta else 0
            nodes.append([(x - 24) // 48, (y - 24) // 48, kind, cost, nm, tip])
            ords.append([n, int(meta.group(2)) if meta else 100])
        lay = {"size": (size - 48) // 48 + 1, "links": links, "nodes": nodes}
        if name in layout and layout[name] != lay:
            # Same board, other class: only skill names should differ.
            prev = layout[name]
            assert prev["links"] == links and len(prev["nodes"]) == len(nodes), (c, name)
            for a, b in zip(prev["nodes"], nodes):
                assert a[:4] == b[:4], (c, name, a, b)
            lay = None
        if lay: layout.setdefault(name, lay)
        order[c][name] = {"spent": spent[c][name], "o": ords, "names": [n[4] for n in nodes], "tips": [n[5] for n in nodes]}
# Per-class names/tips only where they differ from the shared layout.
for c in CLASSES:
    for b, d in order[c].items():
        base = layout[b]["nodes"]
        d["skills"] = {i: [nm, tp] for i, (nm, tp) in enumerate(zip(d.pop("names"), d.pop("tips"))) if [nm, tp] != base[i][4:]}
with open(out, "w") as f:
    f.write("// Daevanion boards from aion2-meta.com (scraped " + "2026-10-27" + "): the global layout,\n")
    f.write("// and per class the suggested unlock order and the share of top KR players\n")
    f.write("// taking each node. Generated by plus/scrape_daev.py; don't edit by hand.\n")
    f.write("// DAEV_LAYOUT[board] = { size (grid cells a side), links (SVG path, 48px cells),\n")
    f.write("//   nodes: [[col, row, kind, cost, name, tip]] }\n")
    f.write("// DAEV_ORDER[class][board] = { spent (top players' median), o: [[order, pct]] per node,\n")
    f.write("//   skills: {node index: [name, tip]} where the class's skill differs from the layout }\n")
    f.write("const DAEV_LAYOUT = " + json.dumps(layout, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("const DAEV_ORDER = " + json.dumps(order, ensure_ascii=False, separators=(",", ":")) + ";\n")
for c in CLASSES:
    print(c, {b: (d["spent"], len(d["o"]), len(d["skills"])) for b, d in order[c].items()})
print({b: (l["size"], len(l["nodes"])) for b, l in layout.items()})
